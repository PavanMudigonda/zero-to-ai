#!/usr/bin/env node
/**
 * migrate-from-nextra.mjs
 *
 * Demonstrates migrating the Zero to AI curriculum from the Nextra/Next.js site
 * (`next-docs/`) to Docusaurus (`docusaurus-site/`).
 *
 * What it does
 * ------------
 *  1. Reads the top-level sidebar order/titles from
 *     `next-docs/src/app/_meta.ts`.
 *  2. For each selected chapter it converts the Jupyter notebook(s) that the
 *     Nextra site rendered via the custom <DynamicNotebook> component into plain
 *     Markdown docs:
 *        - markdown cells  -> raw markdown
 *        - code cells      -> ```python fenced blocks
 *     (LaTeX `$...$` and ```mermaid blocks are preserved and rendered by the
 *      Docusaurus remark-math / theme-mermaid pipeline.)
 *  3. Writes Docusaurus front matter (`title`, `sidebar_position`, `format: md`)
 *     and a `_category_.json` per chapter so the autogenerated sidebar reproduces
 *     the exact ordering from `_meta.ts`.
 *
 * Notes
 * -----
 *  - `format: md` forces CommonMark parsing so raw notebook markdown (which may
 *    contain `{`, `}`, or `<...>`) does not break the MDX compiler.
 *  - By default only a representative subset of chapters is migrated to keep the
 *    demo reviewable. Pass `--all` to migrate every chapter listed in _meta.ts.
 *
 * Usage
 * -----
 *   node scripts/migrate-from-nextra.mjs           # representative subset
 *   node scripts/migrate-from-nextra.mjs --all      # all chapters
 */

import { promises as fs } from 'node:fs';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SITE_ROOT = path.resolve(__dirname, '..');
const REPO_ROOT = path.resolve(SITE_ROOT, '..');
const NEXTRA_APP = path.join(REPO_ROOT, 'next-docs', 'src', 'app');
const DOCS_OUT = path.join(SITE_ROOT, 'docs');

const MIGRATE_ALL = process.argv.includes('--all');

/** Representative subset that exercises notebooks, sub-pages, math and mermaid. */
const DEMO_SUBSET = new Set([
  '00-course-setup',
  '01-python',
  '02-data-science',
  '08-rag',
  '15-ai-agents',
]);

/**
 * Parse a Nextra `_meta.ts` file into an ordered list of entries.
 * Only string-valued entries become navigable pages; object entries
 * (e.g. `auth: { display: 'hidden' }`) are treated as non-pages.
 */
async function parseMeta(metaPath) {
  if (!existsSync(metaPath)) return [];
  const raw = await fs.readFile(metaPath, 'utf8');
  const entries = [];
  // Match: "key": "label"   OR   key: "label"   OR   "key": {   OR   key: {
  const re = /["']?([\w.-]+)["']?\s*:\s*(?:["']([^"']*)["']|(\{))/g;
  let m;
  while ((m = re.exec(raw)) !== null) {
    const [, key, label, isObject] = m;
    entries.push({ key, label: label ?? null, isObject: Boolean(isObject) });
  }
  return entries;
}

/** Join a notebook cell `source` (string | string[]) into a single string. */
function joinSource(source) {
  return Array.isArray(source) ? source.join('') : String(source ?? '');
}

/** Convert a parsed notebook (nbformat JSON) into Markdown. */
function notebookToMarkdown(nb) {
  const out = [];
  for (const cell of nb.cells ?? []) {
    const src = joinSource(cell.source).trimEnd();
    if (!src) continue;

    if (cell.cell_type === 'markdown') {
      out.push(src);
    } else if (cell.cell_type === 'code') {
      const lang = (nb.metadata?.language_info?.name || 'python').toLowerCase();
      out.push('```' + lang + '\n' + src + '\n```');
    }
  }
  return out.join('\n\n') + '\n';
}

/** Strip a leading numeric prefix and turn slug into Title Case. */
function slugToTitle(slug) {
  return slug
    .replace(/^\d+[-_]/, '')
    .replace(/[-_]+/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase())
    .trim();
}

/** Escape `---` thematic breaks that some YAML-ish notebooks place at line start
 *  right after a heading (harmless, but keeps CommonMark output tidy). */
function escapeFrontMatterValue(value) {
  return value.replace(/"/g, '\\"');
}

function frontMatter(fields) {
  const lines = ['---'];
  for (const [k, v] of Object.entries(fields)) {
    if (v === undefined || v === null) continue;
    lines.push(`${k}: ${typeof v === 'number' ? v : `"${escapeFrontMatterValue(String(v))}"`}`);
  }
  lines.push('---', '');
  return lines.join('\n');
}

/** Find the primary notebook for a chapter directory. */
function findMainNotebook(chapterDir, chapterKey) {
  const preferred = path.join(chapterDir, `${chapterKey}.ipynb`);
  if (existsSync(preferred)) return preferred;
  // fallback: first .ipynb directly in the folder
  return null;
}

async function readNotebook(nbPath) {
  const raw = await fs.readFile(nbPath, 'utf8');
  return JSON.parse(raw);
}

async function writeDoc(filePath, contents) {
  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, contents, 'utf8');
}

async function migrateChapter(entry, position) {
  const chapterKey = entry.key;
  const chapterDir = path.join(NEXTRA_APP, chapterKey);
  if (!existsSync(chapterDir)) {
    console.warn(`  ! skipping ${chapterKey} (no directory)`);
    return false;
  }

  const label = entry.label ?? slugToTitle(chapterKey);
  const outDir = path.join(DOCS_OUT, chapterKey);

  // _category_.json drives the autogenerated sidebar label + order.
  await writeDoc(
    path.join(outDir, '_category_.json'),
    JSON.stringify(
      {
        label,
        position,
        link: { type: 'doc', id: 'index' },
      },
      null,
      2,
    ) + '\n',
  );

  // Main chapter notebook -> index.md
  const mainNb = findMainNotebook(chapterDir, chapterKey);
  if (mainNb) {
    const nb = await readNotebook(mainNb);
    const body = notebookToMarkdown(nb);
    const fm = frontMatter({
      title: slugToTitle(chapterKey),
      sidebar_label: 'Overview',
      sidebar_position: 1,
      format: 'md',
    });
    await writeDoc(path.join(outDir, 'index.md'), fm + body);
    console.log(`  ✓ ${chapterKey}/index.md`);
  } else {
    // No notebook: create a stub index so the category link resolves.
    const fm = frontMatter({
      title: slugToTitle(chapterKey),
      sidebar_position: 1,
      format: 'md',
    });
    await writeDoc(
      path.join(outDir, 'index.md'),
      fm + `# ${slugToTitle(chapterKey)}\n\n_Migrated from the Nextra curriculum._\n`,
    );
    console.log(`  ✓ ${chapterKey}/index.md (stub)`);
  }

  // Sub-pages declared in the chapter's own _meta.ts (e.g. 00-course-setup).
  const subEntries = await parseMeta(path.join(chapterDir, '_meta.ts'));
  let subPos = 2;
  for (const sub of subEntries) {
    if (sub.isObject) continue;
    const subDir = path.join(chapterDir, sub.key);
    const subNb = path.join(subDir, `${sub.key}.ipynb`);
    if (!existsSync(subNb)) continue;
    const nb = await readNotebook(subNb);
    const body = notebookToMarkdown(nb);
    const fm = frontMatter({
      title: sub.label ?? slugToTitle(sub.key),
      sidebar_label: sub.label ?? slugToTitle(sub.key),
      sidebar_position: subPos++,
      format: 'md',
    });
    await writeDoc(path.join(outDir, `${sub.key}.md`), fm + body);
    console.log(`  ✓ ${chapterKey}/${sub.key}.md`);
  }

  return true;
}

async function writeHome(chapters) {
  const items = chapters
    .map((c, i) => `${i + 1}. [${c.label}](./${c.key})`)
    .join('\n');
  const fm = frontMatter({
    title: 'Zero to AI',
    slug: '/',
    sidebar_label: 'Home',
    sidebar_position: 0,
    format: 'md',
  });
  const body = `# Zero to AI

An open-source roadmap & curriculum for learning Data Science, Machine Learning,
LLMs, and AI Agents from scratch.

> This site is a **Docusaurus migration demo** of the curriculum that previously
> shipped on Nextra. Content below was generated by \`scripts/migrate-from-nextra.mjs\`
> directly from the original Jupyter notebooks.

## Migrated chapters

${items}
`;
  await writeDoc(path.join(DOCS_OUT, 'index.md'), fm + body);
  console.log('  ✓ index.md (home)');
}

async function main() {
  console.log(`Migrating Nextra -> Docusaurus (${MIGRATE_ALL ? 'all chapters' : 'demo subset'})`);
  console.log(`  source: ${path.relative(REPO_ROOT, NEXTRA_APP)}`);
  console.log(`  target: ${path.relative(REPO_ROOT, DOCS_OUT)}\n`);

  const topMeta = await parseMeta(path.join(NEXTRA_APP, '_meta.ts'));
  const chapters = topMeta.filter(
    (e) => e.key !== 'index' && e.key !== 'auth' && !e.isObject,
  );

  const selected = MIGRATE_ALL
    ? chapters
    : chapters.filter((c) => DEMO_SUBSET.has(c.key));

  // Clean previous generated docs (keep src, config, etc.).
  if (existsSync(DOCS_OUT)) {
    await fs.rm(DOCS_OUT, { recursive: true, force: true });
  }
  await fs.mkdir(DOCS_OUT, { recursive: true });

  const migrated = [];
  let position = 1;
  for (const entry of selected) {
    console.log(`Chapter: ${entry.key}`);
    const ok = await migrateChapter(entry, position++);
    if (ok) migrated.push(entry);
  }

  await writeHome(migrated);

  console.log(`\nDone. Migrated ${migrated.length} chapter(s) into ${path.relative(REPO_ROOT, DOCS_OUT)}.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
